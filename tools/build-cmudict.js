// Builds data/cmudict.js from data/cmudict/cmudict.dict in a compact form the site loads quickly.
//   node tools/build-cmudict.js
// Format: one line per word, sorted. Each line starts with how many leading letters it shares with the
// previous word (a digit 0-9), then the rest of the word, a space, and its pronunciations separated by "|".
// Each ARPABET phone (with its stress digit) is written as one character; the table is stored alongside.
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'data/cmudict/cmudict.dict'), 'utf8').split('\n');

const entries = new Map();
for (let line of src) {
  line = line.split(' #')[0].trim();
  if (!line) continue;
  const sp = line.indexOf(' ');
  const word = line.slice(0, sp).replace(/\(\d+\)$/, '');
  const pron = line.slice(sp + 1).trim();
  if (!entries.has(word)) entries.set(word, []);
  if (!entries.get(word).includes(pron)) entries.get(word).push(pron);
}

const phones = [...new Set([...entries.values()].flat().flatMap((p) => p.split(' ')))].sort();
// Printable ASCII, minus characters that are awkward inside a JavaScript template literal or used as separators.
const alphabet = [];
for (let c = 33; c < 127; c++) if (!'`\\$|{}'.includes(String.fromCharCode(c))) alphabet.push(String.fromCharCode(c));
if (phones.length > alphabet.length) throw new Error('Too many phones: ' + phones.length);
const code = new Map(phones.map((ph, i) => [ph, alphabet[i]]));

const words = [...entries.keys()].sort();
const lines = [];
let prev = '';
for (const w of words) {
  let k = 0;
  while (k < 9 && k < w.length && k < prev.length && w[k] === prev[k]) k++;
  lines.push(k + w.slice(k) + ' ' + entries.get(w).map((p) => p.split(' ').map((x) => code.get(x)).join('')).join('|'));
  prev = w;
}
for (const l of lines) if (/[`\\]|\$\{/.test(l)) throw new Error('Unsafe line: ' + l);

const out = '// Generated by tools/build-cmudict.js from data/cmudict/cmudict.dict (CMU Pronouncing Dictionary, see data/cmudict/LICENSE).\n' +
  '// Do not edit by hand. Compact form: see the comment at the top of tools/build-cmudict.js.\n' +
  '(function (g) {\n' +
  '  g.SMARTIPA_CMUDICT_FORMAT = { version: 2, phones: ' + JSON.stringify(phones.join(' ')) + ', alphabet: ' + JSON.stringify(alphabet.slice(0, phones.length).join('')) + ' };\n' +
  '  g.SMARTIPA_CMUDICT_RAW = String.raw`' + lines.join('\n') + '`;\n' +
  '})(typeof window !== \'undefined\' ? window : globalThis);\n';
fs.writeFileSync(path.join(root, 'data/cmudict.js'), out);
console.log(words.length + ' words, ' + phones.length + ' phones, ' + Buffer.byteLength(out) + ' bytes');
